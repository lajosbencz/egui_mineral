//! Generates `egui_mineral_material`'s `icons` module from the Material Symbols codepoints file of the
//! `egui_material_icons` version in `Cargo.lock`. `generate` is deterministic; it resolves with `--locked`.

use std::{
    collections::{HashMap, HashSet},
    env,
    error::Error,
    fmt::Write as _,
    fs,
    path::Path,
    process::Command,
};

use serde_json::Value;

type Res<T> = Result<T, Box<dyn Error>>;

const SOURCE: &str = "egui_material_icons";
const CODEPOINTS: &str = "MaterialSymbolsRounded-Regular.codepoints";
const OUTPUT: &str = "crates/egui_mineral_material/src/icons.rs";
// Legacy names sharing the codepoint of the name without them: the outline is a separate font.
const OUTLINE_SUFFIXES: [&str; 3] = ["_OUTLINE", "_OUTLINED", "_BORDER"];

fn main() -> Res<()> {
    match env::args().nth(1).as_deref() {
        Some("generate") => generate(),
        _ => Err("usage: material_symbols generate".into()),
    }
}

fn generate() -> Res<()> {
    let meta = metadata()?;
    let package = meta["packages"]
        .as_array()
        .and_then(|ps| ps.iter().find(|p| p["name"] == SOURCE))
        .ok_or("metadata: no egui_material_icons")?;
    let dir = package["manifest_path"]
        .as_str()
        .and_then(|p| Path::new(p).parent())
        .ok_or("metadata: no egui_material_icons manifest")?;
    let version = package["version"]
        .as_str()
        .ok_or("metadata: no egui_material_icons version")?;
    let root = Path::new(meta["workspace_root"].as_str().ok_or("metadata: no workspace_root")?);
    let source = fs::read_to_string(dir.join(CODEPOINTS))?;
    fs::write(root.join(OUTPUT), render(&source, version)?)?;
    Ok(())
}

fn metadata() -> Res<Value> {
    let out = Command::new(env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .args(["metadata", "--format-version", "1", "--locked"])
        .output()?;
    if !out.status.success() {
        return Err(format!("cargo metadata: {}", String::from_utf8_lossy(&out.stderr)).into());
    }
    Ok(serde_json::from_slice(&out.stdout)?)
}

fn render(codepoints: &str, version: &str) -> Res<String> {
    let entries: Vec<(String, &str)> = codepoints
        .lines()
        .filter_map(|l| {
            let (name, hex) = l.trim().split_once(' ')?;
            Some((name.to_uppercase(), hex.trim()))
        })
        .collect();
    let mut by_name: HashMap<&str, &str> = HashMap::new();
    for (name, hex) in &entries {
        by_name.entry(name).or_insert(hex);
    }
    let mut seen = HashSet::new();
    let mut out = format!(
        "// @generated by tools/material_symbols from {SOURCE} {version}, do not edit.\n\
         use crate::MaterialIcon;\n\n"
    );
    for (name, hex) in &entries {
        let outline_alias = OUTLINE_SUFFIXES.iter().any(|suffix| {
            name.strip_suffix(suffix)
                .and_then(|base| by_name.get(base))
                .is_some_and(|base_hex| base_hex == hex)
        });
        if outline_alias || !seen.insert(name) {
            continue;
        }
        writeln!(
            out,
            "/// `{}`.\npub const ICON_{name}: MaterialIcon = MaterialIcon::new('\\u{{{hex}}}');",
            name.to_lowercase()
        )?;
    }
    Ok(out)
}
