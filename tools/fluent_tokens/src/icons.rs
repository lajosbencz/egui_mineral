//! `egui_mineral_fluent`'s `icons` module from the vendored Fluent UI System Icons codepoint map.
#![expect(clippy::format_push_string, reason = "text generator")]

use std::{collections::BTreeMap, fs, path::Path};

use crate::Error;

pub(crate) const REPO: &str = "microsoft/fluentui-system-icons";
pub(crate) const FONT: &str = "FluentSystemIcons-Resizable";

#[derive(Default)]
struct Pair {
    regular: Option<(u32, String)>,
    filled: Option<(u32, String)>,
}

// `{"ic_fluent_<name>_<size>_<style>[_<variant>]": <codepoint>, ...}`
fn entries(json: &str) -> Result<Vec<(String, u32)>, Error> {
    let body = json
        .trim()
        .strip_prefix('{')
        .and_then(|b| b.strip_suffix('}'))
        .ok_or_else(|| Error::new("codepoint map is not a JSON object"))?;
    body.split(',')
        .filter(|e| !e.trim().is_empty())
        .map(|e| {
            let (k, v) = e
                .split_once(':')
                .ok_or_else(|| Error::new(format!("not a key/value pair: {e:?}")))?;
            let key = k
                .trim()
                .strip_prefix('"')
                .and_then(|k| k.strip_suffix('"'))
                .ok_or_else(|| Error::new(format!("unquoted key: {k:?}")))?;
            let code = v
                .trim()
                .parse::<u32>()
                .map_err(|err| Error::new(format!("{key}: {err}")))?;
            Ok((key.to_owned(), code))
        })
        .collect()
}

fn split(key: &str) -> Result<(String, bool), Error> {
    let rest = key
        .strip_prefix("ic_fluent_")
        .ok_or_else(|| Error::new(format!("{key}: no ic_fluent_ prefix")))?;
    let parts: Vec<&str> = rest.split('_').collect();
    let style = parts
        .iter()
        .rposition(|p| *p == "regular" || *p == "filled")
        .ok_or_else(|| Error::new(format!("{key}: no style")))?;
    let size = style
        .checked_sub(1)
        .and_then(|i| parts.get(i))
        .filter(|s| s.bytes().all(|b| b.is_ascii_digit()))
        .ok_or_else(|| Error::new(format!("{key}: no size before the style")))?;
    if *size != "20" {
        return Err(Error::new(format!("{key}: resizable icons are 20, got {size}")));
    }
    let mut name: Vec<&str> = parts.get(..style - 1).unwrap_or_default().to_vec();
    name.extend(parts.get(style + 1..).unwrap_or_default());
    let filled = parts.get(style) == Some(&"filled");
    Ok((format!("ICON_{}", name.join("_").to_ascii_uppercase()), filled))
}

pub(crate) fn module(sha: &str, copyright: &str, json: &Path) -> Result<String, Error> {
    let text = fs::read_to_string(json).map_err(|e| Error::new(format!("{}: {e}", json.display())))?;
    let mut icons: BTreeMap<String, Pair> = BTreeMap::new();
    for (key, code) in entries(&text)? {
        let (name, filled) = split(&key)?;
        let pair = icons.entry(name.clone()).or_default();
        let slot = if filled { &mut pair.filled } else { &mut pair.regular };
        if slot.replace((code, key)).is_some() {
            return Err(Error::new(format!("{name}: duplicate style")));
        }
    }
    let mut out = format!(
        "// @generated by tools/fluent_tokens from {REPO}@{sha}, do not edit.\n\
         // fonts/{FONT}.json\n// {copyright}\n// Licensed under the MIT License; see NOTICE.\n\
         //! Fluent UI System Icons of the bundled resizable font, regular and filled.\n\
         //!\n//! Icons without a filled (regular) form use the other form for both.\n\nuse crate::FluentIcon;\n\n\
         /// `{REPO}` commit of the font.\npub const SOURCE_COMMIT: &str = \"{sha}\";\n"
    );
    for (name, pair) in &icons {
        let (regular, filled) = match (&pair.regular, &pair.filled) {
            (Some(r), Some(f)) => (r, f),
            (Some(one), None) | (None, Some(one)) => (one, one),
            (None, None) => return Err(Error::new(format!("{name}: no glyph"))),
        };
        let doc = if regular.1 == filled.1 {
            format!("`{}`", regular.1)
        } else {
            format!("`{}`, `{}`", regular.1, filled.1)
        };
        out.push_str(&format!(
            "/// {doc}.\npub const {name}: FluentIcon = FluentIcon::new('\\u{{{:x}}}', '\\u{{{:x}}}');\n",
            regular.0, filled.0
        ));
    }
    Ok(out)
}
