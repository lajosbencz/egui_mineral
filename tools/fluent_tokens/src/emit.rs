//! Rust source for the generated `spec::tokens` modules.
#![expect(clippy::format_push_string, reason = "text generator")]

use std::collections::BTreeMap;

use crate::{
    REPO, SOURCE_DIR,
    model::{AliasToken, BRAND_STEPS, Model, Palette, Rgba, Swatch, VARIANT_KEYS},
};

pub(crate) fn const_name(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        let prev = i.checked_sub(1).and_then(|p| chars.get(p)).copied();
        let next = chars.get(i + 1).copied();
        let split = match prev {
            None => false,
            Some(p) if c.is_ascii_uppercase() => {
                p.is_ascii_lowercase()
                    || (p.is_ascii_digit() && next.is_some_and(|n| n.is_ascii_lowercase()))
                    || (p.is_ascii_uppercase() && next.is_some_and(|n| n.is_ascii_lowercase()))
            }
            Some(p) => c.is_ascii_digit() && p.is_ascii_alphabetic(),
        };
        if split {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

fn variant_name(token: &str) -> String {
    let mut chars = token.chars();
    chars
        .next()
        .map_or_else(String::new, |c| c.to_uppercase().chain(chars).collect())
}

fn color(c: Rgba) -> String {
    match c {
        Rgba { r, g, b, a: 255 } => format!("Color32::from_rgb({r}, {g}, {b})"),
        Rgba { r: 0, g: 0, b: 0, a: 0 } => "Color32::TRANSPARENT".to_owned(),
        Rgba { r, g, b, a } => format!("Color32::from_rgba_unmultiplied_const({r}, {g}, {b}, {a})"),
    }
}

fn header(sha: &str, copyright: &str, sources: &[&str]) -> String {
    let mut out = format!("// @generated by tools/fluent_tokens from {REPO}@{sha}, do not edit.\n");
    for s in sources {
        out.push_str(&format!("// {SOURCE_DIR}/{s}\n"));
    }
    out.push_str(&format!(
        "// {copyright}\n// Licensed under the MIT License; see NOTICE.\n"
    ));
    out
}

fn consts<T>(out: &mut String, items: &[(String, T)], ty: &str, value: impl Fn(&T) -> String) {
    for (name, v) in items {
        out.push_str(&format!(
            "/// `{name}`.\npub const {}: {ty} = {};\n",
            const_name(name),
            value(v)
        ));
    }
}

fn floats(out: &mut String, items: &[(String, f32)]) {
    consts(out, items, "f32", |v| format!("{v:?}"));
}

fn palette(h: &str, p: &Palette) -> String {
    let mut out = format!(
        "{h}//! Global color palettes (`global/colors.ts`).\n\nuse egui::Color32;\n\n\
         /// Twelve-step ramp of one named color (`ColorVariants`).\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct ColorVariants {{\n"
    );
    for key in VARIANT_KEYS {
        out.push_str(&format!("    /// `{key}`.\n    pub {key}: Color32,\n"));
    }
    out.push_str("}\n\n");
    for (name, c) in &p.scalars {
        out.push_str(&format!(
            "/// `{name}`.\npub const {}: Color32 = {};\n",
            const_name(name),
            color(*c)
        ));
    }
    for (table, entries) in &p.numeric {
        out.push('\n');
        for (key, c) in entries {
            out.push_str(&format!(
                "/// `{table}[{key}]`.\npub const {}_{key}: Color32 = {};\n",
                const_name(table),
                color(*c)
            ));
        }
    }
    for (name, ramp) in &p.variants {
        out.push_str(&format!(
            "\n/// `{name}`.\npub const {}: ColorVariants = ColorVariants {{\n",
            const_name(name)
        ));
        for (key, c) in VARIANT_KEYS.iter().zip(ramp) {
            out.push_str(&format!("    {key}: {},\n", color(*c)));
        }
        out.push_str("};\n");
    }
    out
}

fn brand(h: &str, ramp: &[Rgba; BRAND_STEPS]) -> String {
    let mut out = format!(
        "{h}//! Brand ramps (`global/brandColors.ts`).\n\nuse egui::Color32;\n\n\
         /// Step of a [`BrandRamp`], from 10 (darkest) to 160 (lightest).\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum BrandStep {{\n"
    );
    for i in 1..=BRAND_STEPS {
        out.push_str(&format!("    /// `{}`.\n    S{},\n", i * 10, i * 10));
    }
    out.push_str(
        "}\n\n/// Brand color ramp (`BrandVariants`); alias color tokens resolve their brand steps against it.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct BrandRamp(pub [Color32; 16]);\n\n\
         impl BrandRamp {\n    /// Color at `step`.\n    pub const fn step(&self, step: BrandStep) -> Color32 {\n        \
         self.0[step as usize]\n    }\n}\n\n\
         /// `brandWeb`, the Fluent web brand.\npub const BRAND_WEB: BrandRamp = BrandRamp([\n",
    );
    for c in ramp {
        out.push_str(&format!("    {},\n", color(*c)));
    }
    out.push_str("]);\n");
    out
}

fn geometry(h: &str, m: &Model) -> String {
    let mut out = format!("{h}//! Border radii, stroke widths and spacings in points.\n\n");
    floats(&mut out, &m.radii);
    out.push('\n');
    floats(&mut out, &m.strokes);
    out.push('\n');
    floats(&mut out, &m.spacings);
    out
}

fn typography(h: &str, m: &Model) -> String {
    let mut out = format!("{h}//! Font sizes and line heights in points, weights and CSS font family stacks.\n\n");
    floats(&mut out, &m.font_sizes);
    out.push('\n');
    floats(&mut out, &m.line_heights);
    out.push('\n');
    consts(&mut out, &m.font_weights, "u16", ToString::to_string);
    out.push('\n');
    consts(&mut out, &m.font_families, "&str", |v| format!("{v:?}"));
    out
}

fn motion(h: &str, m: &Model) -> String {
    let mut out = format!(
        "{h}//! Durations and easing curves.\n\nuse std::time::Duration;\n\nuse egui_mineral::motion::CubicBezier;\n\n"
    );
    consts(&mut out, &m.durations, "Duration", |v| {
        format!("Duration::from_millis({v})")
    });
    out.push('\n');
    consts(&mut out, &m.curves, "CubicBezier", |[a, b, c, d]| {
        format!("CubicBezier::new({a:?}, {b:?}, {c:?}, {d:?})")
    });
    out
}

fn shadow(h: &str, m: &Model) -> String {
    let mut out = format!(
        "{h}//! Elevation shadows, two layers each.\n//!\n\
         //! The layers are colored by [`ColorNeutralShadowAmbient`](super::color::ColorToken::ColorNeutralShadowAmbient) and\n\
         //! [`ColorNeutralShadowKey`](super::color::ColorToken::ColorNeutralShadowKey), or the `ColorBrandShadow*` pair for\n\
         //! brand shadows.\n\n\
         /// One shadow layer in points.\n#[derive(Clone, Copy, Debug, PartialEq)]\npub struct ShadowLayer {{\n    \
         /// Horizontal offset.\n    pub x: f32,\n    /// Vertical offset.\n    pub y: f32,\n    /// Blur radius.\n    pub blur: f32,\n}}\n\n\
         /// Ambient and key layer of one elevation level.\n#[derive(Clone, Copy, Debug, PartialEq)]\npub struct Shadow {{\n    \
         /// Wide, faint layer.\n    pub ambient: ShadowLayer,\n    /// Offset layer.\n    pub key: ShadowLayer,\n}}\n"
    );
    for (name, [ambient, key]) in &m.shadows {
        out.push_str(&format!(
            "\n/// `{name}`.\npub const {}: Shadow = Shadow {{\n",
            const_name(name)
        ));
        for (field, l) in [("ambient", ambient), ("key", key)] {
            out.push_str(&format!(
                "    {field}: ShadowLayer {{\n        x: {:?},\n        y: {:?},\n        blur: {:?},\n    }},\n",
                l.x, l.y, l.blur
            ));
        }
        out.push_str("};\n");
    }
    out
}

fn swatch(s: &Swatch) -> String {
    match s {
        Swatch::Rgba(c) => format!("Swatch::Fixed({})", color(*c)),
        Swatch::Const(n) => format!("Swatch::Fixed(palette::{n})"),
        Swatch::Brand(step) => format!("Swatch::Brand(BrandStep::S{step})"),
    }
}

fn fixed(s: &Swatch) -> String {
    match s {
        Swatch::Rgba(c) => color(*c),
        Swatch::Const(n) => format!("palette::{n}"),
        Swatch::Brand(_) => String::new(),
    }
}

fn alias(h: &str, tokens: &[AliasToken]) -> String {
    let n = tokens.len();
    let mut out = format!(
        "{h}//! Alias color tokens of the Fluent 2 web light, web dark and high contrast themes.\n\n\
         use egui::Color32;\n\n\
         use super::{{\n    brand::{{BrandRamp, BrandStep}},\n    palette,\n}};\n\n\
         /// Alias color token (`colorNeutralForeground1`, ...), resolved per theme.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum ColorToken {{\n"
    );
    for t in tokens {
        out.push_str(&format!("    /// `{}`.\n    {},\n", t.name, variant_name(&t.name)));
    }
    out.push_str("}\n\n#[derive(Clone, Copy)]\nenum Swatch {\n    Fixed(Color32),\n    Brand(BrandStep),\n}\n\n");
    out.push_str(
        "impl Swatch {\n    const fn resolve(self, brand: &BrandRamp) -> Color32 {\n        match self {\n            \
         Self::Fixed(color) => color,\n            Self::Brand(step) => brand.step(step),\n        }\n    }\n}\n\n",
    );
    for (name, pick) in [
        (
            "WEB_LIGHT",
            (|t: &AliasToken| swatch(&t.light)) as fn(&AliasToken) -> String,
        ),
        ("WEB_DARK", |t| swatch(&t.dark)),
    ] {
        out.push_str(&format!("static {name}: [Swatch; {n}] = [\n"));
        for t in tokens {
            out.push_str(&format!("    {},\n", pick(t)));
        }
        out.push_str("];\n\n");
    }
    out.push_str(&format!("static HIGH_CONTRAST: [Color32; {n}] = [\n"));
    for t in tokens {
        out.push_str(&format!("    {},\n", fixed(&t.high_contrast)));
    }
    out.push_str("];\n\n");
    out.push_str(&format!(
        "impl ColorToken {{\n    /// Every token, in declaration order.\n    pub const ALL: [Self; {n}] = [\n"
    ));
    for t in tokens {
        out.push_str(&format!("        Self::{},\n", variant_name(&t.name)));
    }
    out.push_str(
        "    ];\n\n    /// Color in the web light theme; brand steps come from `brand`.\n    \
         pub const fn web_light(self, brand: &BrandRamp) -> Color32 {\n        WEB_LIGHT[self as usize].resolve(brand)\n    }\n\n    \
         /// Color in the web dark theme; brand steps come from `brand`.\n    \
         pub const fn web_dark(self, brand: &BrandRamp) -> Color32 {\n        WEB_DARK[self as usize].resolve(brand)\n    }\n\n    \
         /// Color in the high contrast theme, which has no brand.\n    \
         pub const fn high_contrast(self) -> Color32 {\n        HIGH_CONTRAST[self as usize]\n    }\n}\n",
    );
    out
}

pub(crate) fn files(sha: &str, copyright: &str, m: &Model) -> BTreeMap<String, String> {
    let h = |sources: &[&str]| header(sha, copyright, sources);
    let mut files = BTreeMap::new();
    files.insert("palette.rs".to_owned(), palette(&h(&["global/colors.ts"]), &m.palette));
    files.insert(
        "brand.rs".to_owned(),
        brand(&h(&["global/brandColors.ts"]), &m.brand_web),
    );
    files.insert(
        "geometry.rs".to_owned(),
        geometry(
            &h(&["global/borderRadius.ts", "global/strokeWidths.ts", "global/spacings.ts"]),
            m,
        ),
    );
    files.insert("typography.rs".to_owned(), typography(&h(&["global/fonts.ts"]), m));
    files.insert(
        "motion.rs".to_owned(),
        motion(&h(&["global/durations.ts", "global/curves.ts"]), m),
    );
    files.insert(
        "shadow.rs".to_owned(),
        shadow(&h(&["utils/shadows.ts", "utils/createLightTheme.ts"]), m),
    );
    files.insert(
        "color.rs".to_owned(),
        alias(
            &h(&[
                "alias/lightColor.ts",
                "alias/lightColorPalette.ts",
                "alias/darkColor.ts",
                "alias/darkColorPalette.ts",
                "alias/highContrastColor.ts",
                "alias/highContrastColorPalette.ts",
            ]),
            &m.tokens,
        ),
    );
    files.insert(
        "mod.rs".to_owned(),
        format!(
            "// @generated by tools/fluent_tokens, do not edit.\n//! Fluent UI React v9 design tokens, one module per token family.\n\n\
             /// `{REPO}` commit of the token sources.\npub const SOURCE_COMMIT: &str = \"{sha}\";\n\n\
             pub mod brand;\npub mod color;\npub mod geometry;\npub mod motion;\npub mod palette;\npub mod shadow;\npub mod typography;\n"
        ),
    );
    files
}
